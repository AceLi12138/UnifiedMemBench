def load_checkpoint_v2(checkpoint_path: str, policy: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    """
    Load a checkpoint and return (checkpoint_data, migrated_from_legacy).
    v2 format:
      {
        "version": 2,
        "policy": {...},
        "dialogues": {"0": {"components": {"1:2": {...}}}}
      }
    """
    if not os.path.exists(checkpoint_path):
        return {
            "version": 2,
            "policy": policy,
            "dialogues": {},
        }, False

    with open(checkpoint_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if isinstance(data, dict) and data.get("version") == 2 and "dialogues" in data:
        data["policy"] = policy
        for dialogue in data.get("dialogues", {}).values():
            components = dialogue.get("components", {})
            for comp in components.values():
                comp.setdefault("task_type", "")
                comp.setdefault("component_text", "")
                comp.setdefault("patch_turns", [])
                comp.setdefault("coverage_report", {})
                comp.setdefault("coverage_decision", {})
                comp.setdefault("judge_source", "")
                comp.setdefault("judge_votes", {})
                comp.setdefault("role_applied_should_verify", True)
                comp.setdefault("role_applied_source", "")
                comp.setdefault("sync_rounds_used", 0)
                comp.setdefault("strict_gate_passed", False)
                comp.setdefault("strict_fail_reason_code", "")
                comp.setdefault("strict_fail_reason_text", "")
                comp.setdefault("strict_fail_evidence_turns", [])
                comp.setdefault("same_task_regression_count", 0)
                comp.setdefault("failure_artifacts", {
                    "last_patch_turns": [],
                    "last_reason": "",
                    "coverage_decision": {},
                })
        return data, False

    # Legacy format migration: {"dialogue_idx": [patches...]}.
    migrated = {
        "version": 2,
        "policy": policy,
        "dialogues": {},
    }
    if isinstance(data, dict):
        for d_idx_str, patches in data.items():
            if not isinstance(patches, list):
                continue
            dialogue_slot = migrated["dialogues"].setdefault(str(d_idx_str), {"components": {}})
            components = dialogue_slot["components"]
            for patch in patches:
                if not isinstance(patch, dict):
                    continue
                t_idx = patch.get("task_idx", -1)
                c_idx = patch.get("comp_idx", -1)
                c_key = component_key(t_idx, c_idx)
                success = bool(patch.get("success"))
                components[c_key] = {
                    "task_idx": t_idx,
                    "comp_idx": c_idx,
                    "task_type": patch.get("task_type", ""),
                    "component_text": patch.get("component_text", ""),
                    "insert_turn": patch.get("insert_turn", 0),
                    "strategy": patch.get("strategy", ""),
                    "status": "success" if success else "failed",
                    "attempts_total": 1,
                    "last_reason": "migrated_success" if success else "migrated_failed",
                    "patch_turns": patch.get("patch_turns", []) if success else [],
                    "accepted_single_turn": False,
                    "coverage_report": {},
                    "coverage_decision": {},
                    "judge_source": "",
                    "judge_votes": {},
                    "role_applied_should_verify": True,
                    "role_applied_source": "",
                    "sync_rounds_used": 0,
                    "strict_gate_passed": False,
                    "strict_fail_reason_code": "",
                    "strict_fail_reason_text": "",
                    "strict_fail_evidence_turns": [],
                    "same_task_regression_count": 0,
                    "failure_artifacts": {
                        "last_patch_turns": patch.get("patch_turns", []) if not success else [],
                        "last_reason": "migrated_failed" if not success else "",
                        "coverage_decision": {},
                    },
                }

    return migrated, True


