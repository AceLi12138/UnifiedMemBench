def find_insert_position(
    missing_comp: Dict,
    all_details: List[Dict],
    dialogue: List[Dict],
    tasks: List[Dict],
) -> Tuple[int, str]:
    """
    Choose the insertion position for a missing component.
    Uses question semantics and sibling components' temporal/topic relations.
    Returns: (insert_turn_idx, strategy_description)

    Strategy:
    1. Collect positions of existing sibling components in the same task.
    2. Place the missing component according to its temporal/content role in the causal chain.
    3. Insert near sibling components, after the previous sibling or before the next sibling.
    4. Fall back to topic-keyword search or proportional placement.
    """
    task_idx = missing_comp['task_idx']
    comp_idx = missing_comp['comp_idx']
    comp_text = missing_comp['component_text']
    total_turns = len(dialogue)

    # Prefer evidence anchors from strict evaluation to align repair position with the audit decision.
    preferred_turns = []
    for key in ("evidence_turns", "matched_turns"):
        turns = missing_comp.get(key, [])
        if isinstance(turns, list):
            preferred_turns.extend(
                int(t) for t in turns
                if isinstance(t, int) or (isinstance(t, str) and t.isdigit())
            )
    preferred_turns = sorted({t for t in preferred_turns if 0 <= t < total_turns})
    if preferred_turns:
        anchor = preferred_turns[len(preferred_turns) // 2]
        insert_at = min(anchor + 1, total_turns - 1)
        return insert_at, f"near strict evidence anchor (turn {anchor})"

    # --- Collect location information for all components in the same task. ---
    # {comp_idx: (status, [matched_turns], component_text)}
    sibling_info = {}
    for d in all_details:
        if d['task_idx'] == task_idx:
            sibling_info[d['comp_idx']] = {
                'status': d['final_status'],
                'turns': d.get('matched_turns', []),
                'text': d['component_text'],
            }

    # Find all existing siblings as (comp_idx, representative_turn), sorted by comp_idx.
    present_siblings = []
    for ci, info in sorted(sibling_info.items()):
        if info['status'] == 'PRESENT' and info['turns']:
            # Use the median matched turn as the representative position.
            sorted_turns = sorted(info['turns'])
            median_turn = sorted_turns[len(sorted_turns) // 2]
            present_siblings.append((ci, median_turn))

    # --- Strategy 1: locate previous/next siblings by component index and insert between them. ---
    if present_siblings:
        # Find the nearest existing previous and next siblings in component order.
        prev_sibling = None  # comp_idx < current and closest.
        next_sibling = None  # comp_idx > current and closest.

        for ci, turn in present_siblings:
            if ci < comp_idx:
                if prev_sibling is None or ci > prev_sibling[0]:
                    prev_sibling = (ci, turn)
            elif ci > comp_idx:
                if next_sibling is None or ci < next_sibling[0]:
                    next_sibling = (ci, turn)

        if prev_sibling and next_sibling:
            # Insert between previous and next siblings, biased after the previous sibling.
            insert_at = prev_sibling[1] + 2
            insert_at = min(insert_at, next_sibling[1] - 1)
            insert_at = max(0, min(insert_at, total_turns - 1))
            return insert_at, (
                f"component {comp_idx} between sibling [{prev_sibling[0]}] "
                f"(turn {prev_sibling[1]}) and sibling [{next_sibling[0]}] "
                f"(turn {next_sibling[1]})"
            )
        elif prev_sibling:
            # Only previous sibling exists; insert after it.
            insert_at = min(prev_sibling[1] + 2, total_turns - 1)
            return insert_at, f"component {comp_idx} after sibling [{prev_sibling[0]}] (turn {prev_sibling[1]})"
        elif next_sibling:
            # Only next sibling exists; insert before it.
            insert_at = max(0, next_sibling[1] - 2)
            return insert_at, f"component {comp_idx} before sibling [{next_sibling[0]}] (turn {next_sibling[1]})"

    # --- Strategy 2: use dates to search for a relevant time span in the dialogue. ---
    dates = re.findall(r'\d{4}-\d{2}-\d{2}', comp_text)
    if dates:
        target_date = dates[0]
        year = target_date[:4]
        # Search turns mentioning the year and choose the middle candidate.
        candidates = []
        for i, turn in enumerate(dialogue):
            if year in turn['content']:
                candidates.append(i)
        if candidates:
            # Use the middle position.
            mid = candidates[len(candidates) // 2]
            return min(mid + 1, total_turns - 1), f"near turns mentioning year {year} (turn {mid})"

    # --- Strategy 3: use keywords to find the most topic-relevant position. ---
    keywords = re.findall(r'\b[a-zA-Z]{5,}\b', comp_text.lower())
    if keywords:
        best_turn = -1
        best_count = 0
        for i in range(0, total_turns, 5):
            window_text = ' '.join(
                t['content'].lower() for t in dialogue[max(0, i-3):min(total_turns, i+3)]
            )
            count = sum(1 for kw in keywords if kw in window_text)
            if count > best_count:
                best_count = count
                best_turn = i

        if best_turn >= 0 and best_count >= 2:
            return min(best_turn + 1, total_turns - 1), \
                f"topic keyword match ({best_count}/{len(keywords)} keywords, turn {best_turn})"

    # --- Strategy 4: assign position proportionally by task order. ---
    task_count = len(tasks)
    if task_count > 0:
        ratio = (task_idx + 0.5) / task_count
        position = 0.05 + ratio * 0.9
        insert_at = int(position * total_turns)
        return insert_at, f"proportional placement (task {task_idx}/{task_count}, position {position:.0%})"

    return total_turns // 2, "default midpoint position"


