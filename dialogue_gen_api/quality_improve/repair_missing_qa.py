def load_baseline_role_index(report: Dict[str, Any]) -> Dict[Tuple[int, int, int], Dict[str, Any]]:
    """Extract component role and status index from the baseline strict report."""
    index: Dict[Tuple[int, int, int], Dict[str, Any]] = {}
    for result in report.get("results", []) or []:
        try:
            dialogue_idx = int(result.get("dialogue_idx", -1))
        except (TypeError, ValueError):
            continue
        for detail in result.get("details", []) or []:
            try:
                task_idx = int(detail.get("task_idx", -1))
                comp_idx = int(detail.get("comp_idx", -1))
            except (TypeError, ValueError):
                continue
            if dialogue_idx < 0 or task_idx < 0 or comp_idx < 0:
                continue
            should_verify = detail.get("should_verify")
            if should_verify is None:
                should_verify = str(detail.get("final_status", "")).upper() != "SKIPPED"
            index[(dialogue_idx, task_idx, comp_idx)] = {
                "should_verify": bool(should_verify),
                "component_role": str(detail.get("component_role", "")),
                "final_status": str(detail.get("final_status", "")),
            }
    return index


def _sync_temperature_next(
    current_temp: float,
    last_reason: str,
    temp_min: float,
    temp_max: float,
) -> float:
    reason = (last_reason or "").lower()
    next_temp = float(current_temp)
    if any(tok in reason for tok in ("evidence", "not_enough", "missing_slot", "llm_missing")):
        next_temp += 0.05
    elif any(tok in reason for tok in ("conflict", "regression", "over", "strict_compatible_fail")):
        next_temp -= 0.05
    elif reason.startswith("parse_") or "unparseable" in reason:
        next_temp -= 0.05
    return max(temp_min, min(temp_max, next_temp))


def _collect_verify_keys_for_sync(
    rt: RepairTask,
    tasks: List[Dict[str, Any]],
    role_index: Dict[Tuple[int, int, int], Dict[str, Any]],
    sync_verify_scope: str,
) -> List[Tuple[int, int]]:
    keys = {(rt.task_idx, rt.comp_idx)}
    if sync_verify_scope != "target_plus_same_task":
        return sorted(keys)

    if rt.task_idx < 0 or rt.task_idx >= len(tasks):
        return sorted(keys)
    comps = tasks[rt.task_idx].get("answer_components", []) or []
    for idx in range(len(comps)):
        role = role_index.get((rt.dialogue_idx, rt.task_idx, idx), {})
        if role.get("should_verify", True):
            keys.add((rt.task_idx, idx))
    return sorted(keys)


def run_sync_strict_gate(
    strict_module: Any,
    dialogue_data: Dict[str, Any],
    dialogue_idx: int,
    target_task_idx: int,
    target_comp_idx: int,
    verify_keys: List[Tuple[int, int]],
    role_index: Dict[Tuple[int, int, int], Dict[str, Any]],
    baseline_status_index: Dict[Tuple[int, int, int], str],
    strict_llm: Optional[LLM],
    llm_fallback: Optional[LLM],
    strict_fail_reason: bool,
    strict_eval_kwargs: Dict[str, Any],
) -> Tuple[bool, Dict[str, Any]]:
    """Run strict recheck gating inside the repair pipeline."""
    details = strict_module.evaluate_task_components(
        dialogue_data=dialogue_data,
        dialogue_idx=dialogue_idx,
        component_keys=verify_keys,
        llm=strict_llm,
        llm_fallback=llm_fallback,
        use_llm=True,
        **strict_eval_kwargs,
    )

    detail_map: Dict[Tuple[int, int], Any] = {(d.task_idx, d.comp_idx): d for d in details}
    target_detail = detail_map.get((target_task_idx, target_comp_idx))
    target_present = bool(target_detail and str(target_detail.final_status) == "PRESENT")

    same_task_regressions: List[Dict[str, Any]] = []
    for task_idx, comp_idx in verify_keys:
        if task_idx != target_task_idx:
            continue
        base_key = (dialogue_idx, task_idx, comp_idx)
        role = role_index.get(base_key, {})
        if not role.get("should_verify", True):
            continue
        if baseline_status_index.get(base_key) != "PRESENT":
            continue
        comp_detail = detail_map.get((task_idx, comp_idx))
        if comp_detail is None:
            continue
        if str(comp_detail.final_status) == "MISSING":
            same_task_regressions.append({
                "task_idx": task_idx,
                "comp_idx": comp_idx,
                "reason": str(comp_detail.decision_reason_code or comp_detail.reason or ""),
            })

    gate_ok = target_present and not same_task_regressions
    reason_payload = {
        "reason_code": "",
        "reason_text": "",
        "evidence_turns": [],
        "suggested_fix_focus": "",
    }
    if not gate_ok and strict_fail_reason:
        if not target_present and target_detail is not None:
            reason_payload = strict_module.explain_missing_reason(target_detail)
        elif same_task_regressions:
            reason_payload = {
                "reason_code": "same_task_regression",
                "reason_text": "Patch introduced regression on same-task present component.",
                "evidence_turns": [],
                "suggested_fix_focus": "Avoid altering semantics that invalidate existing same-task components.",
            }

    return gate_ok, {
        "target_present": target_present,
        "same_task_regressions": same_task_regressions,
        "reason_payload": reason_payload,
        "details": [asdict(d) for d in details],
    }


def build_affected_manifest(
    source_report_path: str,
    dialogues_input_path: str,
    dialogues_output_path: str,
    successful_items: List[Dict[str, Any]],
    eval_by_idx: Dict[int, Dict[str, Any]],
    neighbor_window: int = 8,
) -> Dict[str, Any]:
    """Build an affected-component manifest for later targeted rechecks."""
    affected: List[Dict[str, Any]] = []
    seen = set()

    def _add(dialogue_idx: int, task_idx: int, comp_idx: int, source: str):
        key = (int(dialogue_idx), int(task_idx), int(comp_idx), source)
        if key in seen:
            return
        seen.add(key)
        affected.append({
            "dialogue_idx": int(dialogue_idx),
            "task_idx": int(task_idx),
            "comp_idx": int(comp_idx),
            "source": source,
        })

    for item in successful_items:
        d_idx = int(item.get("dialogue_idx", -1))
        t_idx = int(item.get("task_idx", -1))
        c_idx = int(item.get("comp_idx", -1))
        insert_turn = int(item.get("insert_turn", 0))
        inserted_count = int(item.get("inserted_turn_count", 1))
        _add(d_idx, t_idx, c_idx, "direct_repair")

        eval_r = eval_by_idx.get(d_idx, {})
        details = eval_r.get("details", []) or []
        low = insert_turn - neighbor_window
        high = insert_turn + inserted_count + neighbor_window
        for detail in details:
            dt = int(detail.get("task_idx", -1))
            dc = int(detail.get("comp_idx", -1))
            if dt < 0 or dc < 0:
                continue
            if dt == t_idx and dc != c_idx:
                _add(d_idx, dt, dc, "same_task")
            turns = []
            for key in ("matched_turns", "evidence_turns"):
                turns.extend(detail.get(key, []) or [])
            turns_norm = []
            for turn in turns:
                try:
                    turns_norm.append(int(turn))
                except (TypeError, ValueError):
                    continue
            if turns_norm and any(low <= t <= high for t in turns_norm):
                _add(d_idx, dt, dc, "neighbor_overlap")

    return {
        "source_report_path": source_report_path,
        "dialogues_input_path": dialogues_input_path,
        "dialogues_output_path": dialogues_output_path,
        "successful_repairs": successful_items,
        "affected_components": affected,
        "neighbor_window": int(neighbor_window),
    }


