async def execute_repair(
    repair_task: RepairTask,
    dialogue: List[Dict],
    llm: LLM,
    semaphore: asyncio.Semaphore,
    min_patch_turns: int = 1,
    coverage_mode: str = "key_elements_strict",
    repair_max_tokens: int = 500,
    repair_temperature: float = 0.7,
    parse_log_path: Optional[str] = None,
    coverage_judge_llm: Optional[LLM] = None,
    coverage_judge_votes: int = 3,
    coverage_judge_min_pass_votes: int = 2,
    coverage_judge_max_tokens: int = 256,
    coverage_judge_log_path: Optional[str] = None,
    attempt_no: int = 1,
    patch_mode: str = "minimal_semantic",
    patch_turn_mode: str = "single_assistant",
    strict_fail_reason: Optional[Dict[str, Any]] = None,
    strict_success_gate: bool = False,
) -> RepairTask:
    """Execute one repair task."""
    async with semaphore:
        prompt = build_patch_prompt(
            character=repair_task.character,
            component_text=repair_task.component_text,
            task_type=repair_task.task_type,
            dialogue=dialogue,
            insert_turn=repair_task.insert_turn,
            query=repair_task.query,
            answer_components=repair_task.answer_components,
            target_component_idx=repair_task.target_component_idx,
            constraint_spec=repair_task.constraint_spec,
            patch_mode=patch_mode,
            patch_turn_mode=patch_turn_mode,
            strict_fail_reason=strict_fail_reason,
        )

        try:
            completion = await llm.inference(
                prompt,
                max_tokens=repair_max_tokens,
                temperature=repair_temperature,
            )
            response = llm.decode(completion)
            parse_result = parse_patch_response(response, min_turns=min_patch_turns)
            repair_task.turn_count = parse_result.turn_count

            if not parse_result.ok:
                repair_task.patch_turns = []
                repair_task.success = False
                repair_task.parse_reason = f"parse_{parse_result.reason}"
                repair_task.coverage_ok = False
                repair_task.coverage_report = {}
                repair_task.coverage_decision = {}
                repair_task.judge_source = ""
                repair_task.judge_votes = {}

                completion_tokens = None
                finish_reason = None
                if isinstance(completion, dict):
                    usage = completion.get("usage", {})
                    completion_tokens = usage.get("completion_tokens")
                    choice0 = completion.get("choices", [{}])[0]
                    if isinstance(choice0, dict):
                        finish_reason = choice0.get("finish_reason")

                append_jsonl(parse_log_path, {
                    "dialogue_idx": repair_task.dialogue_idx,
                    "task_idx": repair_task.task_idx,
                    "comp_idx": repair_task.comp_idx,
                    "attempt": attempt_no,
                    "reason": repair_task.parse_reason,
                    "turn_count": repair_task.turn_count,
                    "response_len": len(response),
                    "finish_reason": finish_reason,
                    "completion_tokens": completion_tokens,
                    "component_text": repair_task.component_text,
                    "response_head": parse_result.raw_excerpt,
                })
                return repair_task

            repair_task.patch_turns = parse_result.turns
            repair_task.accepted_single_turn = (parse_result.turn_count == 1)
            repair_task.parse_reason = "ok"
            repair_task.judge_source = ""
            repair_task.judge_votes = {}
            repair_task.coverage_decision = {}

            coverage_ok, coverage_report = validate_patch_coverage(
                repair_task.component_text,
                parse_result.turns,
                mode=coverage_mode,
            )
            repair_task.coverage_ok = bool(coverage_ok)
            repair_task.coverage_report = coverage_report

            if coverage_mode == "hybrid_llm":
                hard_facts_ok = bool(coverage_report.get("hard_facts_ok", True))
                if not hard_facts_ok:
                    repair_task.coverage_ok = False
                    repair_task.coverage_report = coverage_report
                    repair_task.coverage_decision = {
                        "mode": "hybrid_llm",
                        "result": "fail_hard_facts",
                    }
                    repair_task.success = False
                    repair_task.parse_reason = "coverage_fail_hard_fact"
                    return repair_task

                if coverage_report.get("rule_fast_pass"):
                    repair_task.coverage_ok = True
                    repair_task.coverage_report = coverage_report
                    repair_task.coverage_decision = {
                        "mode": "hybrid_llm",
                        "result": "rule_fast_pass",
                    }
                    repair_task.judge_source = "rule_fast_pass"
                else:
                    judge_llm = coverage_judge_llm or llm
                    judge_ok, judge_report = await judge_patch_coverage_with_votes(
                        repair_task,
                        judge_llm,
                        max_tokens=coverage_judge_max_tokens,
                        votes=coverage_judge_votes,
                        min_pass_votes=coverage_judge_min_pass_votes,
                        coverage_judge_log_path=coverage_judge_log_path,
                        attempt_no=attempt_no,
                    )
                    coverage_report["llm_judge"] = judge_report
                    repair_task.coverage_ok = judge_ok
                    repair_task.coverage_report = coverage_report
                    repair_task.coverage_decision = judge_report
                    repair_task.judge_source = "llm_vote"
                    repair_task.judge_votes = {
                        "pass_votes": judge_report.get("pass_votes", 0),
                        "total_votes": judge_report.get("total_votes", 0),
                        "required_pass_votes": judge_report.get("required_pass_votes", 0),
                    }
                    if not judge_ok:
                        repair_task.success = False
                        repair_task.parse_reason = "coverage_fail_llm"
                        return repair_task

            if not repair_task.coverage_ok:
                repair_task.success = False
                repair_task.parse_reason = "coverage_fail"
                return repair_task

            strict_ok, strict_report = validate_strict_compatible_hard_facts(
                repair_task=repair_task,
                patch_turns=parse_result.turns,
            )
            repair_task.coverage_report = dict(repair_task.coverage_report or {})
            repair_task.coverage_report["strict_compatible"] = strict_report
            if not strict_ok and strict_success_gate:
                repair_task.success = False
                repair_task.parse_reason = "strict_compatible_fail"
                return repair_task
            if not strict_ok:
                repair_task.coverage_report["strict_compatible_diagnostic_only"] = True

            repair_task.success = True
        except Exception as e:
            repair_task.patch_turns = []
            repair_task.success = False
            repair_task.parse_reason = "api_error"
            repair_task.last_error = str(e)[:200]
            repair_task.coverage_ok = False
            repair_task.coverage_report = {}
            repair_task.coverage_decision = {}
            repair_task.judge_source = ""
            repair_task.judge_votes = {}
            print(f"  ❌ API error [{repair_task.dialogue_idx}]: {str(e)[:80]}")

    return repair_task


def apply_patches_to_dialogue(dialogue_data: Dict, repairs: List[RepairTask]) -> Dict:
    """
    Apply all patches to a dialogue.
    Note: insert from back to front to avoid index shifts.
    """
    dialogue = dialogue_data['dialogue']

    # Keep successful repair tasks and sort by descending insertion position.
    successful = [r for r in repairs if r.success and r.patch_turns]
    successful.sort(key=lambda r: r.insert_turn, reverse=True)

    total_inserted = 0
    for repair in successful:
        insert_at = repair.insert_turn
        # Keep insertion position within range.
        insert_at = min(insert_at, len(dialogue))
        # Insert patch turns.
        for j, patch_turn in enumerate(reversed(repair.patch_turns)):
            dialogue.insert(insert_at, patch_turn)
        total_inserted += len(repair.patch_turns)

    # Update statistics.
    if 'statistics' in dialogue_data:
        dialogue_data['statistics']['total_turns'] = len(dialogue)
        dialogue_data['statistics']['estimated_tokens'] = len(
            json.dumps(dialogue, ensure_ascii=False)
        ) // 4

    return dialogue_data


