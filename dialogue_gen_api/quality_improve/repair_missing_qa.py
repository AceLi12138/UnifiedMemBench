def _extract_must_include(component_text: str) -> str:
    """
    Extract key elements that must appear in the patch, such as dates, proper nouns,
    numbers, and key phrases. Returns a clear must-include list for the LLM.
    """
    items = []

    # Extract YYYY-MM-DD dates.
    dates = re.findall(r'\d{4}-\d{2}-\d{2}', component_text)
    for d in dates:
        parts = d.split('-')
        month_names = {'01':'January','02':'February','03':'March','04':'April',
                      '05':'May','06':'June','07':'July','08':'August',
                      '09':'September','10':'October','11':'November','12':'December'}
        month = month_names.get(parts[1], parts[1])
        day = int(parts[2])
        items.append(f'Date "{month} {day}, {parts[0]}" (must say this exact date)')

    # Extract proper nouns, excluding sentence-initial capitalization.
    proper_nouns = re.findall(r'(?<!^)(?<!\. )(?<!\n)[A-Z][a-z]{2,}(?:\s+[A-Z][a-z]+)*', component_text)
    # Deduplicate and exclude months/common words.
    common = {'The', 'This', 'That', 'She', 'Her', 'His', 'They', 'Their', 'Event',
              'January','February','March','April','May','June','July','August',
              'September','October','November','December', 'Start', 'End', 'Initial',
              'Foundation', 'Final', 'Key', 'Career', 'Personal', 'Resulting',
              'Intermediate', 'Bridge', 'Correction', 'Tradition', 'Location',
              'Refinement', 'Apprenticeship', 'Assignment', 'Presentation'}
    for pn in proper_nouns:
        if pn not in common and len(pn) > 2:
            items.append(f'Name/Place "{pn}"')

    # Extract independent numbers outside dates and normalize thousands separators.
    text_no_dates = re.sub(r'\d{4}-\d{2}-\d{2}', ' ', component_text)
    text_no_dates = re.sub(r'\b\d{1,3}(?:,\d{3})+\b', lambda m: m.group(0).replace(',', ''), text_no_dates)
    numbers = []
    seen_numbers = set()
    for n_raw in re.findall(r'\b\d+\b', text_no_dates):
        try:
            n = str(int(n_raw))
        except ValueError:
            n = n_raw
        if n == "000":
            continue
        # Exclude standalone years to avoid duplicating date constraints.
        if n.isdigit() and len(n) == 4 and 1900 <= int(n) <= 2100:
            continue
        if n not in seen_numbers:
            seen_numbers.add(n)
            numbers.append(n)
    for n in numbers:
        items.append(f'Number "{n}"')

    # Extract key phrases after removing dates and labels.
    text_clean = re.sub(r'\d{4}-\d{2}-\d{2}', '', component_text)
    text_clean = re.sub(r'^(Start date|End date|Calculation|Correction|Tradition|Location|'
                        r'Date|Requirement|Status|Project|Quality|Action|Shift|'
                        r'New Status|Behavior|Gift|Dates|Result|Mindset shift|'
                        r'Initial cause|Intermediate step|Key development|Bridge event|'
                        r'Final effect|Foundation|Resulting Journey|Final Outcome|'
                        r'Event [A-Z]):\s*', '', text_clean, flags=re.IGNORECASE)
    # Use core verb/noun-like phrases.
    words = text_clean.split()
    if len(words) >= 3:
        # Use the first few meaningful words as a key phrase.
        key_words = [w for w in words if len(w) > 3 and w[0].islower()][:4]
        if key_words:
            phrase = ' '.join(key_words)
            items.append(f'Key phrase: use words like "{phrase}"')

    return items


def build_patch_prompt(
    character: str,
    component_text: str,
    task_type: str,
    dialogue: List[Dict],
    insert_turn: int,
    query: str = "",
    context_size: int = 4,
    answer_components: Optional[List[str]] = None,
    target_component_idx: int = -1,
    constraint_spec: Optional[Dict[str, Any]] = None,
    patch_mode: str = "minimal_semantic",
    patch_turn_mode: str = "single_assistant",
    strict_fail_reason: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Build the prompt for LLM patch-dialogue generation.
    Extracts key dates, nouns, and numbers from the component and requires them verbatim.
    """
    total = len(dialogue)
    answer_components = answer_components or []
    constraint_spec = constraint_spec or {}
    patch_mode = (patch_mode or "minimal_semantic").strip().lower()
    patch_turn_mode = (patch_turn_mode or "single_assistant").strip().lower()

    pre_text = "(omitted in minimal_semantic mode)"
    post_text = "(omitted in minimal_semantic mode)"
    start_role = "assistant"
    if patch_mode == "legacy_contextual":
        pre_start = max(0, insert_turn - context_size)
        preceding = dialogue[pre_start:insert_turn]
        post_end = min(total, insert_turn + context_size)
        following = dialogue[insert_turn:post_end]

        pre_lines = []
        for t in preceding:
            role = "User" if t['role'] == 'user' else character
            pre_lines.append(f'{role}: {t["content"][:250]}')
        pre_text = "\n".join(pre_lines) if pre_lines else "(conversation start)"

        post_lines = []
        for t in following:
            role = "User" if t['role'] == 'user' else character
            post_lines.append(f'{role}: {t["content"][:250]}')
        post_text = "\n".join(post_lines) if post_lines else "(conversation end)"

        if insert_turn > 0:
            prev_role = dialogue[insert_turn - 1]['role']
            start_role = "user" if prev_role == "assistant" else "assistant"
        else:
            start_role = "user"

    # Extract must-include key elements.
    must_include_items = _extract_must_include(component_text)
    if must_include_items:
        must_include_str = "\n".join(f"  - {item}" for item in must_include_items)
        must_include_section = f"""
MANDATORY ELEMENTS ({character} MUST use these exact words/dates in the dialogue):
{must_include_str}
"""
    else:
        must_include_section = ""

    # Context hint.
    context_hint = ""
    if query and task_type:
        context_hint = f"""
CONTEXT (for understanding only - do NOT reveal this in dialogue):
This is part of a {task_type} task about {character}'s life story."""
    query_hint = ""
    if query:
        query_hint = f"""
QUESTION FOR ALIGNMENT ONLY (PRIVATE, DO NOT EXPOSE):
{query}"""
    components_hint = ""
    if answer_components:
        lines = []
        for idx, comp in enumerate(answer_components):
            marker = " (TARGET)" if idx == target_component_idx else ""
            lines.append(f"{idx}. {comp}{marker}")
        components_hint = "\nALL ANSWER COMPONENTS (PRIVATE REFERENCE):\n" + "\n".join(lines)

    constraint_hint = ""
    if constraint_spec:
        concise = {
            "hard_slots": constraint_spec.get("hard_slots", []),
            "soft_slots": constraint_spec.get("soft_slots", []),
            "slot_values": constraint_spec.get("slot_values", {}),
        }
        constraint_hint = (
            "\nCONSTRAINT SPEC (PRIVATE REFERENCE):\n"
            + json.dumps(concise, ensure_ascii=False)
        )

    strict_fail_hint = ""
    if strict_fail_reason:
        strict_fail_hint = (
            "\nSTRICT FAILURE FROM PREVIOUS ATTEMPT (PRIVATE):\n"
            f"- reason_code: {strict_fail_reason.get('reason_code', '')}\n"
            f"- reason_text: {strict_fail_reason.get('reason_text', '')}\n"
            f"- suggested_fix_focus: {strict_fail_reason.get('suggested_fix_focus', '')}\n"
        )

    if patch_mode == "minimal_semantic":
        if patch_turn_mode == "single_assistant":
            turn_instruction = "Generate exactly 1 turn with role=\"assistant\"."
            output_template = '[{"role":"assistant","content":"..."}]'
        else:
            turn_instruction = "Generate exactly 2 turns."
            output_template = (
                '[{"role":"assistant","content":"..."},'
                '{"role":"user","content":"..."}]'
            )
        return f"""You are a dialogue patch generator. Create a minimal semantic patch that expresses ONLY the target component.

CHARACTER: {character}

TARGET COMPONENT TO EMBED:
"{component_text}"
{must_include_section}{context_hint}{query_hint}{components_hint}{constraint_hint}{strict_fail_hint}

RULES:
1. {turn_instruction}
2. Keep content minimal and factual: only what is needed to express TARGET COMPONENT.
3. Do NOT add new events, new entities, new causal chains, or extra timeline details.
4. Dates and numbers must match TARGET COMPONENT (equivalent date format allowed).
5. For numeric amounts, always include canonical plain digits without commas (e.g., 15000 not 15,000).
6. Use the private question only as hidden alignment guidance; do NOT quote or paraphrase the question in dialogue.
7. Output ONLY raw JSON array, no markdown and no extra text.
8. Each item must include exactly: role, content.

{output_template}"""

    prompt = f"""You are a dialogue patch generator. Create 2-4 natural dialogue turns that embed specific information between the given context.

CHARACTER: {character}

INFORMATION TO EMBED:
"{component_text}"
{must_include_section}{context_hint}{query_hint}{components_hint}{constraint_hint}{strict_fail_hint}

PRECEDING CONTEXT:
{pre_text}

FOLLOWING CONTEXT:
{post_text}

RULES:
1. Generate exactly 2 or 4 turns. First turn from "{start_role}".
2. {character} MUST naturally weave ALL mandatory elements above into the dialogue.
3. Dates MUST appear as "Month Day, Year" (e.g., "April 20, 2022"), NOT as vague references like "that spring" or "around that time".
4. All names, locations, and numbers from the information MUST appear verbatim.
5. The key facts should appear together in the SAME turn (not scattered across turns).
6. Flow naturally from preceding into following context.
7. No quiz questions, no meta-comments about the task, no stage directions, no brackets like [] or <>.
8. Use the private question only as hidden alignment guidance; do NOT quote or paraphrase the question in dialogue.
9. OUTPUT FORMAT IS CRITICAL: you MUST output ONLY a raw JSON array, with NO extra text before or after it.
10. Do NOT add explanations, comments, markdown, ``` fences, or any other content outside the JSON.
11. Each item in the array MUST be an object with exactly two fields: "role" ("user" or "assistant" only) and "content" (string).

[
  {{"role": "{start_role}", "content": "..."}},
  {{"role": "{"assistant" if start_role == "user" else "user"}", "content": "..."}}
]"""

    return prompt


def build_coverage_judge_prompt(
    query: str,
    task_type: str,
    answer_components: List[str],
    target_component_idx: int,
    target_component_text: str,
    patch_turns: List[Dict],
) -> str:
    """Build the semantic coverage-judge prompt."""
    patch_lines = []
    for turn in patch_turns:
        if not isinstance(turn, dict):
            continue
        role = str(turn.get("role", "")).strip() or "unknown"
        content = str(turn.get("content", "")).strip()
        patch_lines.append(f"- {role}: {content}")
    patch_text = "\n".join(patch_lines) if patch_lines else "(empty)"

    component_lines = []
    for idx, comp in enumerate(answer_components):
        marker = " (TARGET)" if idx == target_component_idx else ""
        component_lines.append(f"{idx}. {comp}{marker}")
    components_text = "\n".join(component_lines) if component_lines else "(no components)"

    return f"""You are a strict semantic evaluator for QA coverage.

Evaluate whether the PATCH dialogue completes the TARGET answer component for this QA task.

TASK TYPE:
{task_type}

QUESTION (Q):
{query}

ALL ANSWER COMPONENTS (A):
{components_text}

TARGET COMPONENT:
index={target_component_idx}
text={target_component_text}

PATCH DIALOGUE:
{patch_text}

Rules:
1. Date and number facts must stay accurate.
2. The target component must be clearly completed in meaning, not word-for-word.
3. Using other components does not count as completing the target component.
4. Ignore style; judge only factual and semantic completion.
5. Output JSON only. No markdown.

Required JSON schema:
{{
  "pass": true/false,
  "event_complete": true/false,
  "date_correct": true/false,
  "number_correct": true/false,
  "used_target_component": true/false,
  "missing_points": ["..."],
  "conflicts": ["..."],
  "reason": "one short sentence"
}}"""


def _to_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    if isinstance(value, str):
        lowered = value.strip().lower()
        return lowered in {"1", "true", "yes", "y", "pass", "ok"}
    return False


def parse_coverage_judge_response(response: str) -> Tuple[bool, Dict[str, Any], str]:
    """Parse the semantic coverage-judge response."""
    if not response:
        return False, {}, "empty_response"

    text = response.strip()
    text = re.sub(r'^\s*```(?:json)?\s*', '', text, flags=re.IGNORECASE)
    text = re.sub(r'\s*```\s*$', '', text)
    text = text.strip()

    candidates = [text]
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        candidates.append(text[start:end + 1])

    for candidate in candidates:
        try:
            parsed = json.loads(candidate)
        except json.JSONDecodeError:
            continue

        if isinstance(parsed, list) and parsed and isinstance(parsed[0], dict):
            parsed = parsed[0]
        if not isinstance(parsed, dict):
            continue

        normalized = {
            "pass": _to_bool(parsed.get("pass", parsed.get("verdict", False))),
            "event_complete": _to_bool(parsed.get("event_complete", False)),
            "date_correct": _to_bool(parsed.get("date_correct", True)),
            "number_correct": _to_bool(parsed.get("number_correct", True)),
            "used_target_component": _to_bool(parsed.get("used_target_component", True)),
            "missing_points": parsed.get("missing_points", []),
            "conflicts": parsed.get("conflicts", []),
            "reason": str(parsed.get("reason", "")).strip(),
        }
        if not isinstance(normalized["missing_points"], list):
            normalized["missing_points"] = [str(normalized["missing_points"])]
        if not isinstance(normalized["conflicts"], list):
            normalized["conflicts"] = [str(normalized["conflicts"])]
        return True, normalized, "ok"

    return False, {}, "unparseable"


def _extract_turn_list(payload: Any) -> Optional[List[Dict]]:
    """Extract a candidate turn list from model output."""
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for key in ('turns', 'patch_turns', 'dialogue', 'patch', 'data'):
            value = payload.get(key)
            if isinstance(value, list):
                return value
    return None


def _normalize_turns(turns: List[Dict]) -> Tuple[Optional[List[Dict]], str]:
    """Normalize common field/role variants to role/content."""
    if not isinstance(turns, list) or not turns:
        return None, "empty_turns"

    normalized = []
    for idx, turn in enumerate(turns):
        if not isinstance(turn, dict):
            return None, f"turn_not_dict_{idx}"

        role = turn.get('role', turn.get('speaker'))
        content = turn.get('content', turn.get('text'))

        if not isinstance(role, str) or not isinstance(content, str):
            return None, f"missing_field_{idx}"

        role_norm = role.strip().lower()
        role_aliases = {
            'user': 'user',
            'human': 'user',
            'assistant': 'assistant',
            'ai': 'assistant',
            'bot': 'assistant',
        }
        role_norm = role_aliases.get(role_norm, role_norm)
        if role_norm not in ('user', 'assistant'):
            return None, f"invalid_role_{role_norm}"

        normalized.append({
            'role': role_norm,
            'content': content.strip(),
        })

    return normalized, "ok"


def _parse_candidate(candidate: str) -> Tuple[Optional[List[Dict]], str]:
    """Try to parse one candidate text as patch turns."""
    last_reason = "unparseable"
    for parser in (json.loads, ast.literal_eval):
        try:
            payload = parser(candidate)
        except (json.JSONDecodeError, ValueError, SyntaxError):
            continue

        turns = _extract_turn_list(payload)
        if turns is None:
            last_reason = "not_turn_list"
            continue

        normalized, reason = _normalize_turns(turns)
        if normalized is not None:
            return normalized, "ok"
        last_reason = reason

    return None, last_reason


def parse_patch_response(response: str, min_turns: int = 1) -> ParsePatchResult:
    """Parse an LLM-generated patch dialogue."""
    if not response:
        return ParsePatchResult(
            ok=False,
            turns=[],
            reason="empty_response",
            turn_count=0,
            raw_excerpt="",
        )

    text = response.strip()
    text = re.sub(r'^\s*```(?:json)?\s*', '', text, flags=re.IGNORECASE)
    text = re.sub(r'\s*```\s*$', '', text)
    text = text.strip()

    candidates = [text]
    start = text.find('[')
    end = text.rfind(']')
    if start != -1 and end != -1 and end > start:
        candidates.append(text[start:end + 1])

    last_reason = "unparseable"
    for candidate in candidates:
        parsed, reason = _parse_candidate(candidate)
        if parsed is None:
            last_reason = reason
            continue

        turn_count = len(parsed)
        if turn_count < min_turns:
            too_few_reason = "single_turn" if turn_count == 1 else "too_few_turns"
            return ParsePatchResult(
                ok=False,
                turns=parsed,
                reason=too_few_reason,
                turn_count=turn_count,
                raw_excerpt=text[:240],
            )

        return ParsePatchResult(
            ok=True,
            turns=parsed,
            reason="ok",
            turn_count=turn_count,
            raw_excerpt=text[:240],
        )

    return ParsePatchResult(
        ok=False,
        turns=[],
        reason=last_reason,
        turn_count=0,
        raw_excerpt=text[:240],
    )


def _extract_dates(text: str) -> List[str]:
    return re.findall(r'\d{4}-\d{2}-\d{2}', text)


def _date_variants(date_str: str) -> List[str]:
    variants = [date_str]
    months = {
        "01": "january", "02": "february", "03": "march", "04": "april",
        "05": "may", "06": "june", "07": "july", "08": "august",
        "09": "september", "10": "october", "11": "november", "12": "december",
    }
    try:
        year, month, day = date_str.split("-")
        month_name = months.get(month)
        day_i = int(day)
        if month_name:
            variants.extend([
                f"{month_name} {day_i}, {year}",
                f"{month_name} {day_i} {year}",
                f"{month_name} {day_i}",
                f"{month_name} {year}",
            ])
    except (ValueError, IndexError):
        pass
    return variants


def _extract_numbers_without_dates(component_text: str) -> List[str]:
    stripped = re.sub(r'\d{4}-\d{2}-\d{2}', ' ', component_text or "")
    # Normalize thousands separators first so "15,000" is not split into "15" and "000".
    stripped = re.sub(
        r'\b\d{1,3}(?:,\d{3})+\b',
        lambda m: m.group(0).replace(',', ''),
        stripped,
    )
    nums = []
    seen = set()
    for raw in re.findall(r'\b\d+\b', stripped):
        try:
            norm = str(int(raw))
        except ValueError:
            norm = raw
        if norm == "000":
            continue
        if norm not in seen:
            seen.add(norm)
            nums.append(norm)
    return sorted(nums)


def _extract_entities(component_text: str) -> List[str]:
    entities = re.findall(r'\b[A-Z][a-z]+(?:\s+[A-Z][a-z]+)*\b', component_text)
    common = {
        "The", "This", "That", "She", "He", "They", "Their", "His", "Her",
        "January", "February", "March", "April", "May", "June", "July",
        "August", "September", "October", "November", "December",
    }
    cleaned = []
    for entity in entities:
        if entity not in common:
            cleaned.append(entity)
    # Deduplicate while preserving order.
    dedup = []
    seen = set()
    for entity in cleaned:
        key = entity.lower()
        if key not in seen:
            seen.add(key)
            dedup.append(entity)
    return dedup


def _extract_keywords(component_text: str) -> List[str]:
    stop_words = {
        "this", "that", "with", "from", "they", "them", "their", "have",
        "been", "were", "will", "would", "could", "should", "about", "after",
        "before", "during", "between", "into", "through", "being", "each",
        "which", "what", "when", "where", "than", "then", "also", "just",
        "more", "most", "some", "very", "much", "such", "only", "over",
        "same", "other", "event", "date",
    }
    words = re.findall(r'\b[a-zA-Z]{4,}\b', component_text.lower())
    dedup = []
    seen = set()
    for word in words:
        if word in stop_words:
            continue
        if word not in seen:
            seen.add(word)
            dedup.append(word)
    return dedup[:12]


def validate_hard_facts(component_text: str, patch_turns: List[Dict]) -> Tuple[bool, Dict[str, Any]]:
    """Check only hard facts: dates and numbers."""
    patch_text = " ".join(t.get("content", "") for t in patch_turns if isinstance(t, dict))
    patch_lower = patch_text.lower()

    dates = _extract_dates(component_text)
    numbers = _extract_numbers_without_dates(component_text)

    date_hits = {}
    for date in dates:
        variants = _date_variants(date)
        hit = any(v.lower() in patch_lower for v in variants)
        date_hits[date] = hit

    number_hits = {}
    for number in numbers:
        number_hits[number] = bool(re.search(rf'\b{re.escape(number)}\b', patch_text))

    dates_ok = all(date_hits.values()) if dates else True
    numbers_ok = all(number_hits.values()) if numbers else True
    hard_ok = dates_ok and numbers_ok
    return hard_ok, {
        "ok": hard_ok,
        "dates": {
            "required": dates,
            "hits": date_hits,
            "ok": dates_ok,
        },
        "numbers": {
            "required": numbers,
            "hits": number_hits,
            "ok": numbers_ok,
        },
    }


def _build_soft_signal_report(component_text: str, patch_turns: List[Dict]) -> Dict[str, Any]:
    """Build soft signals used only to decide whether semantic judging is needed."""
    patch_text = " ".join(t.get("content", "") for t in patch_turns if isinstance(t, dict))
    patch_lower = patch_text.lower()

    entities = _extract_entities(component_text)
    keywords = _extract_keywords(component_text)

    entity_hits = {}
    for entity in entities:
        entity_hits[entity] = entity.lower() in patch_lower

    keyword_hits = {kw: (kw in patch_lower) for kw in keywords}
    entity_matched = sum(1 for hit in entity_hits.values() if hit)
    keyword_matched = sum(1 for hit in keyword_hits.values() if hit)
    entity_ratio = (entity_matched / len(entities)) if entities else 1.0
    keyword_ratio = (keyword_matched / len(keywords)) if keywords else 1.0

    if keywords:
        if len(keywords) <= 2:
            keywords_ok = keyword_matched == len(keywords)
        else:
            keywords_ok = keyword_ratio >= 0.5
    else:
        keywords_ok = True

    return {
        "entities": {
            "required": entities,
            "hits": entity_hits,
            "matched": entity_matched,
            "total": len(entities),
            "ratio": round(entity_ratio, 4),
            "ok": entity_ratio >= 0.5 if entities else True,
        },
        "keywords": {
            "required": keywords,
            "hits": keyword_hits,
            "matched": keyword_matched,
            "total": len(keywords),
            "ratio": round(keyword_ratio, 4),
            "ok": keywords_ok,
        },
    }


def validate_patch_coverage(
    component_text: str,
    patch_turns: List[Dict],
    mode: str = "key_elements_strict",
) -> Tuple[bool, Dict[str, Any]]:
    """Validate whether the patch covers key information in the component."""
    if mode not in ("key_elements_strict", "hybrid_llm"):
        return True, {
            "mode": mode,
            "ok": True,
            "note": "unsupported_mode_fallback",
        }

    hard_ok, hard_report = validate_hard_facts(component_text, patch_turns)
    soft_report = _build_soft_signal_report(component_text, patch_turns)

    if mode == "key_elements_strict":
        entities_ok = soft_report["entities"]["ok"]
        keywords_ok = soft_report["keywords"]["ok"]
        overall_ok = hard_ok and entities_ok and keywords_ok
        report = {
            "mode": mode,
            "ok": overall_ok,
            "dates": hard_report["dates"],
            "numbers": hard_report["numbers"],
            "entities": {
                "required": soft_report["entities"]["required"],
                "hits": soft_report["entities"]["hits"],
                "ok": entities_ok,
            },
            "keywords": {
                "required": soft_report["keywords"]["required"],
                "hits": soft_report["keywords"]["hits"],
                "ok": keywords_ok,
            },
        }
        return overall_ok, report

    # hybrid_llm: require hard facts first, fast-pass by keywords, and send the rest to LLM semantic judging.
    keyword_ok = soft_report["keywords"]["ok"]
    rule_fast_pass = hard_ok and keyword_ok
    report = {
        "mode": mode,
        "ok": rule_fast_pass,
        "hard_facts_ok": hard_ok,
        "rule_fast_pass": rule_fast_pass,
        "needs_llm_judge": hard_ok and not rule_fast_pass,
        "hard_facts": hard_report,
        "soft_signals": soft_report,
    }
    return rule_fast_pass, report


async def judge_patch_coverage_with_votes(
    repair_task: RepairTask,
    llm: LLM,
    max_tokens: int = 256,
    votes: int = 3,
    min_pass_votes: int = 2,
    coverage_judge_log_path: Optional[str] = None,
    attempt_no: int = 1,
) -> Tuple[bool, Dict[str, Any]]:
    """Judge semantic coverage completeness with multiple LLM votes."""
    total_votes = max(1, int(votes))
    required_pass = max(1, min(int(min_pass_votes), total_votes))
    pass_votes = 0
    details = []

    prompt = build_coverage_judge_prompt(
        query=repair_task.query,
        task_type=repair_task.task_type,
        answer_components=repair_task.answer_components,
        target_component_idx=repair_task.target_component_idx,
        target_component_text=repair_task.target_component_text or repair_task.component_text,
        patch_turns=repair_task.patch_turns or [],
    )

    for vote_idx in range(total_votes):
        completion_tokens = None
        finish_reason = None
        raw_response = ""
        ok = False
        parsed = {}
        reason = "judge_error"
        try:
            completion = await llm.inference(prompt, max_tokens=max_tokens)
            raw_response = llm.decode(completion)
            ok, parsed, reason = parse_coverage_judge_response(raw_response)
            if isinstance(completion, dict):
                usage = completion.get("usage", {})
                completion_tokens = usage.get("completion_tokens")
                choice0 = completion.get("choices", [{}])[0]
                if isinstance(choice0, dict):
                    finish_reason = choice0.get("finish_reason")
        except Exception as e:
            reason = f"judge_api_error:{str(e)[:120]}"

        vote_pass = False
        if ok:
            vote_pass = (
                _to_bool(parsed.get("pass"))
                and _to_bool(parsed.get("event_complete"))
                and _to_bool(parsed.get("date_correct"))
                and _to_bool(parsed.get("number_correct"))
                and not parsed.get("conflicts")
            )
        if vote_pass:
            pass_votes += 1

        detail = {
            "vote_index": vote_idx + 1,
            "ok": ok,
            "vote_pass": vote_pass,
            "reason": reason,
            "parsed": parsed,
            "finish_reason": finish_reason,
            "completion_tokens": completion_tokens,
        }
        details.append(detail)
        append_jsonl(coverage_judge_log_path, {
            "dialogue_idx": repair_task.dialogue_idx,
            "task_idx": repair_task.task_idx,
            "comp_idx": repair_task.comp_idx,
            "attempt": attempt_no,
            "vote_index": vote_idx + 1,
            "vote_pass": vote_pass,
            "parse_ok": ok,
            "reason": reason,
            "finish_reason": finish_reason,
            "completion_tokens": completion_tokens,
            "component_text": repair_task.component_text,
            "response_head": raw_response[:240],
            "parsed": parsed,
        })

    final_pass = pass_votes >= required_pass
    return final_pass, {
        "mode": "llm_vote",
        "final_pass": final_pass,
        "pass_votes": pass_votes,
        "required_pass_votes": required_pass,
        "total_votes": total_votes,
        "details": details,
    }


def append_jsonl(path: str, payload: Dict[str, Any]):
    """Append one record to a JSONL log."""
    if not path:
        return
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(payload, ensure_ascii=False) + "\n")


