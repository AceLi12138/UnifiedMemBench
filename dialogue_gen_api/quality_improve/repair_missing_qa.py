def validate_strict_compatible_hard_facts(
    repair_task: RepairTask,
    patch_turns: List[Dict],
) -> Tuple[bool, Dict[str, Any]]:
    """
    Run compatibility validation with strict hard-facts rules.
    Returns (ok, report).
    """
    strict_eval = _load_strict_eval_module()
    if strict_eval is None:
        return True, {"ok": True, "source": "strict_unavailable"}

    dialogue_text_lower = " ".join(
        str(t.get("content", "")).lower()
        for t in (patch_turns or [])
        if isinstance(t, dict)
    )
    constraint_spec = repair_task.constraint_spec if isinstance(repair_task.constraint_spec, dict) else {}
    try:
        status, missing, meta = strict_eval.evaluate_hard_facts(
            component=repair_task.component_text,
            dialogue=patch_turns or [],
            dialogue_text_lower=dialogue_text_lower,
            task_type=repair_task.task_type,
            query=repair_task.query,
            task_profile="qa_task_v1",
            hard_number_mode="contextual_strict",
            return_meta=True,
            constraint_spec=constraint_spec,
        )
    except Exception as e:
        return True, {
            "ok": True,
            "source": "strict_exception_fallback",
            "error": str(e)[:200],
        }

    required_from_report = [str(s).strip() for s in (repair_task.required_slots or []) if str(s).strip()]
    slot_verdicts = meta.get("slot_verdicts", {}) if isinstance(meta, dict) else {}
    slot_missing = [
        slot for slot in required_from_report
        if slot_verdicts.get(slot, True) is False
    ]

    strict_ok = (status != "HARD_MISSING") and not slot_missing
    report = {
        "ok": strict_ok,
        "status": status,
        "missing_facts": missing,
        "slot_missing_from_report": slot_missing,
        "required_slots_report": required_from_report,
        "required_slots_strict": meta.get("required_slots", []) if isinstance(meta, dict) else [],
        "date_equivalent_match_count": int((meta or {}).get("date_equivalent_match_count", 0)) if isinstance(meta, dict) else 0,
    }
    return strict_ok, report


