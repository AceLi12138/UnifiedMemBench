def run_repair(
    dialogues_path: str,
    report_path: str,
    output_path: str,
    model_name: str = "mimo-v2-flash",
    concurrency: int = 10,
    limit: Optional[int] = None,
    max_retries: int = 2,
    min_patch_turns: int = 1,
    max_component_attempts_total: int = 10,
    coverage_mode: str = "hybrid_llm",
    repair_max_tokens: int = 500,
    repair_temperature: float = 0.7,
    parse_log: Optional[str] = None,
    coverage_judge_model: Optional[str] = None,
    coverage_judge_votes: int = 3,
    coverage_judge_min_pass_votes: int = 2,
    coverage_judge_max_tokens: int = 256,
    coverage_judge_log: Optional[str] = None,
    dry_run: bool = False,
    patch_mode: str = "minimal_semantic",
    patch_turn_mode: str = "single_assistant",
    strict_success_gate: bool = True,
    emit_affected_manifest: bool = True,
    affected_manifest_path: Optional[str] = None,
    sync_strict_loop: bool = True,
    sync_verify_scope: str = "target_plus_same_task",
    max_sync_rounds_per_component: int = 12,
    baseline_strict_report: Optional[str] = None,
    role_gate_mode: str = "baseline_lock",
    strict_eval_model: Optional[str] = None,
    strict_fail_reason: bool = True,
    strict_fail_reason_max_tokens: int = 220,
    emit_sync_report: bool = True,
    sync_report_path: Optional[str] = None,
    repair_temperature_mode: str = "adaptive",
    repair_temperature_init: float = 0.65,
    repair_temperature_min: float = 0.60,
    repair_temperature_max: float = 0.80,
):
    """Run the full repair pipeline."""

    # 1. Load data.
    print(f"📂 Loading dialogue data: {dialogues_path}")
    with open(dialogues_path, 'r', encoding='utf-8') as f:
        all_dialogues = json.load(f)
    print(f"  Total dialogues: {len(all_dialogues)}")

    print(f"📂 Loading evaluation report: {report_path}")
    with open(report_path, 'r', encoding='utf-8') as f:
        report = json.load(f)

    eval_results = report.get('results', [])
    print(f"  Evaluation result count: {len(eval_results)}")

    role_gate_mode = (role_gate_mode or "baseline_lock").strip().lower()
    if role_gate_mode not in {"baseline_lock", "baseline_or_fallback"}:
        role_gate_mode = "baseline_lock"

    baseline_report_obj = report
    if baseline_strict_report:
        with open(baseline_strict_report, "r", encoding="utf-8") as f:
            baseline_report_obj = json.load(f)
    elif role_gate_mode == "baseline_lock":
        baseline_report_obj = report
    role_index = load_baseline_role_index(baseline_report_obj)
    baseline_status_index = {
        key: str(value.get("final_status", ""))
        for key, value in role_index.items()
    }

    # 2. Collect missing components and build repair tasks.
    print("\n📋 Collecting missing components...")
    repair_tasks: List[RepairTask] = []
    eval_by_idx = {
        int(r.get("dialogue_idx", -1)): r
        for r in eval_results
        if isinstance(r, dict) and isinstance(r.get("dialogue_idx", None), int)
    }
    seen_components = set()
    role_filtered_skips = 0
    repair_queue = report.get("repair_queue", [])
    use_repair_queue = isinstance(repair_queue, list) and len(repair_queue) > 0

    if use_repair_queue:
        print(f"  Using repair_queue mode: {len(repair_queue)} candidates")
        queue_items = repair_queue
    else:
        print("  repair_queue not found; falling back to legacy details scan mode")
        queue_items = []
        for eval_r in eval_results:
            d_idx = eval_r.get("dialogue_idx", -1)
            details = eval_r.get("details", [])
            for d in details:
                if d.get("final_status") != "MISSING":
                    continue
                if d.get("decision_complete", True) is False:
                    continue
                if d.get("repair_ready", True) is False:
                    continue
                queue_items.append({
                    "dialogue_idx": d_idx,
                    "task_idx": d.get("task_idx", -1),
                    "comp_idx": d.get("comp_idx", -1),
                    "task_type": d.get("task_type", ""),
                    "component_text": d.get("component_text", ""),
                    "matched_turns": d.get("matched_turns", []),
                    "evidence_turns": d.get("evidence_turns", []),
                    "decision_complete": True,
                    "repair_ready": True,
                })

    for item in queue_items:
        if not isinstance(item, dict):
            continue
        if item.get("final_status", "MISSING") != "MISSING":
            continue
        if item.get("decision_complete", True) is False:
            continue
        if item.get("repair_ready", True) is False:
            continue

        d_idx = int(item.get("dialogue_idx", -1))
        t_idx = int(item.get("task_idx", -1))
        c_idx = int(item.get("comp_idx", -1))
        if d_idx < 0 or t_idx < 0 or c_idx < 0:
            continue
        if limit is not None and d_idx >= limit:
            continue
        if d_idx >= len(all_dialogues):
            continue

        role_info = role_index.get((d_idx, t_idx, c_idx))
        if role_info is None and role_gate_mode == "baseline_lock":
            role_filtered_skips += 1
            continue
        should_verify = bool(role_info.get("should_verify", True)) if role_info is not None else True
        if not should_verify:
            role_filtered_skips += 1
            continue

        comp_key = (d_idx, t_idx, c_idx)
        if comp_key in seen_components:
            continue
        seen_components.add(comp_key)

        eval_r = eval_by_idx.get(d_idx, {})
        character = item.get("character") or eval_r.get("character", "")
        dialogue = all_dialogues[d_idx].get("dialogue", [])
        tasks = all_dialogues[d_idx].get("tasks_covered", [])
        details = eval_r.get("details", [])

        component_text = str(item.get("component_text", "")).strip()
        if not component_text:
            continue

        missing_like = {
            "task_idx": t_idx,
            "comp_idx": c_idx,
            "component_text": component_text,
            "matched_turns": item.get("matched_turns", []),
            "evidence_turns": item.get("evidence_turns", []),
        }
        insert_turn, strategy = find_insert_position(missing_like, details, dialogue, tasks)
        query = tasks[t_idx].get('query', '') if t_idx < len(tasks) else ''
        answer_components = tasks[t_idx].get('answer_components', []) if t_idx < len(tasks) else []
        task_type = item.get("task_type") or (tasks[t_idx].get("task_type", "") if t_idx < len(tasks) else "")

        rt = RepairTask(
            dialogue_idx=d_idx,
            task_idx=t_idx,
            comp_idx=c_idx,
            task_type=task_type,
            component_text=component_text,
            character=character,
            query=query,
            answer_components=answer_components,
            target_component_text=component_text,
            target_component_idx=c_idx,
            required_slots=item.get("required_slots", []) or [],
            constraint_spec=item.get("constraint_spec", {}) or {},
            hard_missing_facts=item.get("hard_missing_facts", []) or [],
            hard_initial_status=str(item.get("hard_initial_status", "")),
            insert_turn=insert_turn,
            strategy=strategy,
            role_applied_should_verify=should_verify,
            role_applied_source="baseline" if role_info is not None else "fallback",
        )

        repair_tasks.append(rt)

    print(f"  Components requiring repair: {len(repair_tasks)}")
    print(f"  Components skipped by role filter: {role_filtered_skips}")

    if not repair_tasks:
        print("No components require repair.")
        # Directly copy output.
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(all_dialogues, f, indent=2, ensure_ascii=False)
        return

    # Statistics.
    by_type = {}
    for rt in repair_tasks:
        by_type[rt.task_type] = by_type.get(rt.task_type, 0) + 1
    print("  By task type:")
    for tt, cnt in sorted(by_type.items()):
        print(f"    {tt}: {cnt}")

    # Group by dialogue.
    by_dialogue = {}
    for rt in repair_tasks:
        if rt.dialogue_idx not in by_dialogue:
            by_dialogue[rt.dialogue_idx] = []
        by_dialogue[rt.dialogue_idx].append(rt)

    print(f"  Affected dialogues: {len(by_dialogue)}")

    if dry_run:
        print("\n🔍 Dry run mode: showing repair plan without execution:")
        for d_idx, rts in sorted(by_dialogue.items())[:10]:
            char = rts[0].character
            print(f"\n  [{d_idx}] {char}: {len(rts)} missing components")
            for rt in rts:
                print(f"    task={rt.task_idx}/component={rt.comp_idx}: "
                      f"insert_turn={rt.insert_turn} ({rt.strategy})")
                print(f"      \"{rt.component_text[:80]}...\"")
        return

    if sync_strict_loop:
        print(
            f"\n🔁 Synchronous closed-loop repair (model: {model_name}, strict scope: {sync_verify_scope}, "
            f"temperature mode: {repair_temperature_mode})..."
        )
        llm = get_llm(model_name, max_workers=max(1, concurrency))
        coverage_judge_model_name = coverage_judge_model or model_name
        coverage_judge_llm = llm if coverage_judge_model_name == model_name else get_llm(
            coverage_judge_model_name, max_workers=max(1, concurrency)
        )
        strict_eval_model_name = strict_eval_model or coverage_judge_model_name
        strict_eval_llm = llm if strict_eval_model_name == model_name else get_llm(
            strict_eval_model_name, max_workers=max(1, concurrency)
        )
        strict_eval_fallback = coverage_judge_llm if strict_eval_model_name != coverage_judge_model_name else None
        semaphore = asyncio.Semaphore(max(1, concurrency))
        strict_module = _load_strict_eval_module()
